const { contextBridge, ipcRenderer, webUtils } = require('electron');
const call = ch => (...a) => ipcRenderer.invoke(ch, ...a);
contextBridge.exposeInMainWorld('api', {
  init: call('init'),
  news: call('news'),
  saveSettings: call('settings:save'),
  crashAct: (instId, action) => ipcRenderer.invoke('crash:act', { instId, action }),
  openCrashReport: call('crash:open-report'),
  modUpdates: call('mods:updates'),
  updateAllMods: (id, updates) => ipcRenderer.invoke('mods:update-all', { id, updates }),
  versionPlan: (id, mc) => ipcRenderer.invoke('instance:version-plan', { id, mc }),
  versionApply: (id, mc) => ipcRenderer.invoke('instance:version-apply', { id, mc }),
  selectAccount: call('accounts:select'),
  addAccount: call('accounts:add'),
  renameAccount: (id, name) => ipcRenderer.invoke('accounts:rename', { id, name }),
  removeAccount: call('accounts:remove'),
  renameInstance: (id, name) => ipcRenderer.invoke('instance:rename', { id, name }),
  saveInstance: call('instance:save'),
  deleteInstance: call('instance:delete'),
  openInstance: call('instance:open'),
  launch: (id, opts) => ipcRenderer.invoke('game:launch', id, opts),
  kill: call('game:kill'),
  cancelLaunch: call('game:cancel'),
  searchPacks: call('packs:search'),
  // main.js takes one { id, ... } object for these
  installPack: (id, projectId, type) => ipcRenderer.invoke('packs:install', { id, projectId, type }),
  listPacks: (id, type) => ipcRenderer.invoke('packs:list', { id, type }),
  togglePack: (id, type, file) => ipcRenderer.invoke('packs:toggle', { id, type, file }),
  removePack: (id, type, file) => ipcRenderer.invoke('packs:remove', { id, type, file }),
  pickPacks: (id, folder) => ipcRenderer.invoke('packs:pick', { id, folder }),
  addPacks: (id, paths) => ipcRenderer.invoke('packs:add', { id, paths }),
  pathForFile: (file) => webUtils.getPathForFile(file),
  checkUpdate: call('update:check'),
  applyUpdate: call('update:apply'),
  saveServer: call('servers:save'),
  deleteServer: call('servers:delete'),
  startServer: call('servers:start'),
  stopServer: call('servers:stop'),
  serverCommand: (id, text) => ipcRenderer.invoke('servers:command', { id, text }),
  serverStatus: call('servers:status'),
  startTunnel: call('tunnel:start'),
  stopTunnel: call('tunnel:stop'),
  tunnelState: call('tunnel:get'),
  exportServer: call('servers:export'),
  serverProps: call('servers:props'),
  saveServerProps: (id, values) => ipcRenderer.invoke('servers:props-save', { id, values }),
  serverMods: call('servers:mods-list'),
  searchServerMods: (id, query, offset) => ipcRenderer.invoke('servers:mods-search', { id, query, offset }),
  installServerMod: (id, projectId) => ipcRenderer.invoke('servers:mods-install', { id, projectId }),
  toggleServerMod: (id, file) => ipcRenderer.invoke('servers:mods-toggle', { id, file }),
  removeServerMod: (id, file) => ipcRenderer.invoke('servers:mods-remove', { id, file }),
  pickServerMods: call('servers:mods-pick'),
  serverOptions: (id) => ipcRenderer.invoke('servers:options', id),
  setServerOption: (id, key, value) => ipcRenderer.invoke('servers:set-option', { id, key, value }),
  whitelistAdd: (id, name) => ipcRenderer.invoke('servers:whitelist-add', { id, name }),
  whitelistRemove: (id, name) => ipcRenderer.invoke('servers:whitelist-remove', { id, name }),
  whitelistList: (id) => ipcRenderer.invoke('servers:whitelist-list', id),
  openServerFolder: (id, sub) => ipcRenderer.invoke('servers:open', { id, sub }),
  loadSkin: call('skin:load'),
  saveSkin: call('skin:save'),
  clearSkin: call('skin:clear'),
  lookupSkin: call('skin:lookup'),
  scanImports: call('import:scan'),
  scanImportFolder: call('import:folder'),
  runImport: call('import:run'),
  crooliMods: call('crooli:list'),
  installCrooliMod: (id, modId) => ipcRenderer.invoke('crooli:install', { id, modId }),
  fixConflicts: call('compat:fix'),
  on: (ch, fn) => ipcRenderer.on(ch, (_e, p) => fn(p)),
});
